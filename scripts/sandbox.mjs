import {Worker} from 'near-workspaces';
import assert from 'node:assert/strict';
const worker=await Worker.init();
try {
 const root=worker.rootAccount;
 const contract=await root.createSubAccount('latch',{initialBalance:'10000000000000000000000000'});
 const owner=await root.createSubAccount('owner'), agent=await root.createSubAccount('agent'), other=await root.createSubAccount('other'),recipient=await root.createSubAccount('editor');
 await contract.deploy('artifacts/payoutlatch.wasm');await contract.call(contract,'new',{});
 const amount='100000000000000000000000', deposit='120000000000000000000000';
 const approve=async(who,reference,payee=recipient.accountId)=>who.call(contract,'approve_job',{reference,title:'Sandbox payout',recipient:payee,amount,executor:agent.accountId},{attachedDeposit:deposit});
 const id=await approve(owner,'edit-01');
 await assert.rejects(()=>other.call(contract,'execute',{job_id:id},{gas:'100000000000000'}));
 await assert.rejects(()=>other.call(contract,'cancel',{job_id:id},{gas:'100000000000000'}));
 const before=BigInt((await recipient.balance()).total.toString());
 const outcomes=await Promise.allSettled([owner,agent].map(a=>a.call(contract,'execute',{job_id:id},{gas:'100000000000000'})));
 assert.equal(outcomes.filter(x=>x.status==='fulfilled').length,1);
 assert.equal((await contract.view('get_job',{job_id:id})).status,'Paid');
 assert.equal(BigInt((await recipient.balance()).total.toString())-before,BigInt(amount));
 await assert.rejects(()=>agent.call(contract,'execute',{job_id:id},{gas:'100000000000000'}));
 await assert.rejects(()=>agent.call(contract,'on_transfer',{job_id:id,attempt:1,refund:false},{gas:'100000000000000'}));
 const otherId=await approve(other,'edit-01');assert.notEqual(id,otherId);
 assert.equal((await contract.view('get_jobs',{owner:owner.accountId})).length,1);
 const bad=await approve(owner,'bad-recipient','missing-account.test.near');
 await agent.call(contract,'execute',{job_id:bad},{gas:'100000000000000'});
 assert.equal((await contract.view('get_job',{job_id:bad})).status,'Approved');
 await owner.call(contract,'cancel',{job_id:bad},{gas:'100000000000000'});
 assert.equal((await contract.view('get_job',{job_id:bad})).status,'Cancelled');
 await other.call(contract,'set_executor',{job_id:otherId,executor:null});
 await assert.rejects(()=>agent.call(contract,'execute',{job_id:otherId},{gas:'100000000000000'}));
 await other.call(contract,'cancel',{job_id:otherId},{gas:'100000000000000'});
 console.log('PASS: exact recipient balance, concurrent/replay protection, cross-owner isolation, scoped references, private callback, confirmed failure/refund, revocation.');
} finally {await worker.tearDown();}
