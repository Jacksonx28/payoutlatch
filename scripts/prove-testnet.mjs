import {connect,keyStores,KeyPair} from 'near-api-js';
import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const config=JSON.parse(await readFile('dist/config.json','utf8'));
assert.equal(config.networkId,'testnet');
const root=JSON.parse(await readFile('credentials/testnet-development.json','utf8'));
const keys=new keyStores.InMemoryKeyStore();
await keys.setKey('testnet',root.account_id,KeyPair.fromString(root.private_key));
const near=await connect({networkId:'testnet',nodeUrl:config.rpcUrl,keyStore:keys});
const owner=await near.account(root.account_id);
const run=Date.now().toString(36), accounts={};
for(const label of ['agent','payee','other']){
 const id=`${label}-${run}.${root.account_id}`,key=KeyPair.fromRandom('ed25519');
 await owner.createAccount(id,key.getPublicKey(),'150000000000000000000000');
 await keys.setKey('testnet',id,key);
 accounts[label]={id,key:key.toString()};
}
await writeFile(`credentials/proof-${run}.json`,JSON.stringify(accounts,null,2),{mode:0o600});
const agent=await near.account(accounts.agent.id),other=await near.account(accounts.other.id),payee=await near.account(accounts.payee.id);
const evidence={network:'testnet',contract:config.contractId,createdAt:new Date().toISOString(),deploymentTransaction:config.deploymentTransaction,checks:[],jobs:[]};
const checkpoint=()=>writeFile('dist/evidence.json',JSON.stringify(evidence,null,2)+'\n');
const call=(who,method,args,deposit='0')=>who.functionCall({contractId:config.contractId,methodName:method,args,gas:100000000000000n,attachedDeposit:BigInt(deposit)});
const view=(id)=>owner.viewFunction({contractId:config.contractId,methodName:'get_job',args:{job_id:id}});
const approval=async(reference,recipient=payee.accountId,who=owner)=>{
 const out=await call(who,'approve_job',{reference,title:reference.startsWith('race')?'One payout. Two execution attempts.':reference.startsWith('recovery')?'Failed delivery → owner refund':'Revoked executor',recipient,amount:'1000000000000000000000',executor:agent.accountId},'21000000000000000000000');
 return {id:`${who.accountId}:${reference}`,approval:out.transaction.hash};
};
const job=await approval(`race-${run}`);
const before=BigInt((await payee.state()).amount);
const race=await Promise.allSettled([owner,agent].map(who=>call(who,'execute',{job_id:job.id})));
assert.equal(race.filter(x=>x.status==='fulfilled').length,1);
const paid=await view(job.id);assert.equal(paid.status,'Paid');
assert.equal(BigInt((await payee.state()).amount)-before,1000000000000000000000n);
await assert.rejects(()=>call(agent,'execute',{job_id:job.id}));
evidence.jobs.push({...job,transaction:race.find(x=>x.status==='fulfilled').value.transaction.hash,...paid});
evidence.checks.push('Two concurrent executions: exactly one succeeds; recipient receives exactly 0.001 NEAR.','Replay of a paid job is rejected.');
await checkpoint();
const recovery=await approval(`recovery-${run}`,`missing-${run}.testnet`);
const failed=await call(agent,'execute',{job_id:recovery.id});assert.equal((await view(recovery.id)).status,'Approved');
const refund=await call(owner,'cancel',{job_id:recovery.id});assert.equal((await view(recovery.id)).status,'Cancelled');
evidence.jobs.push({...recovery,failedTransaction:failed.transaction.hash,transaction:refund.transaction.hash,...await view(recovery.id)});
evidence.checks.push('Confirmed transfer failure unlocks the job; owner cancellation refunds principal.');
await checkpoint();
const revoked=await approval(`revoked-${run}`);
await assert.rejects(()=>call(other,'cancel',{job_id:revoked.id}));
await call(owner,'set_executor',{job_id:revoked.id,executor:null});
await assert.rejects(()=>call(agent,'execute',{job_id:revoked.id}));
const cancel=await call(owner,'cancel',{job_id:revoked.id});
evidence.jobs.push({...revoked,transaction:cancel.transaction.hash,...await view(revoked.id)});
evidence.checks.push('Another account cannot cancel; a revoked executor cannot execute.');
await writeFile('dist/evidence.json',JSON.stringify(evidence,null,2)+'\n');
await writeFile('docs/TESTNET_PROOF.md',`# Live testnet evidence\n\nVerified ${evidence.createdAt}. Contract: ${config.contractId}.\n\n${evidence.checks.map(x=>`- ${x}`).join('\n')}\n\n${evidence.jobs.map(j=>`## ${j.title}\n\nJob: \`${j.job_id}\`\n\nFinal state: ${j.status}. [Approval](${config.explorerUrl}/txns/${j.approval}) · [Settlement](${config.explorerUrl}/txns/${j.transaction})${j.failedTransaction?` · [Failed delivery](${config.explorerUrl}/txns/${j.failedTransaction})`:''}`).join('\n\n')}\n`);
console.log(JSON.stringify({result:'PASS',checks:evidence.checks,jobs:evidence.jobs.map(j=>({id:j.job_id,status:j.status,transaction:j.transaction}))},null,2));
